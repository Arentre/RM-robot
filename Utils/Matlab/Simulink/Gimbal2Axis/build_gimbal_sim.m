function build_gimbal_sim()
% 构建适用于 MATLAB/Simulink R2024a 的双轴 GM6020 云台模型。
% 控制器方程对应 User/component/ladrc.c 和 User/module/gimbal.c。
here = fileparts(mfilename('fullpath'));
model = 'gimbal_2axis';
if bdIsLoaded(model), close_system(model, 0); end
new_system(model);
load_system('simulink');
set_param(model, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.002', 'StopTime', '4', 'ReturnWorkspaceOutputs', 'on');

% 电机数据来自 GM6020 手册 v1.4。
% 下列装配参数是假设值，应扫参比较，不能当作实测。
P.Ts = 0.002;
P.Kt = 0.741;              % 牛·米每安
P.Imax = 3.0;              % 单位为 A，指令范围 ±16384
P.Jyaw = 0.015;            % 假定装配惯量，单位为 kg·m²
P.Jpitch = 0.008;          % 假定装配惯量，单位为 kg·m²
P.Byaw = 0.035;            % 假定黏性摩擦，单位为 N·m·s/rad
P.Bpitch = 0.025;
P.pitchGravity = 0.08;     % 假定重力失衡力矩幅值，单位为 N·m
P.yawLadrc = [4, 500, 8, 32, 1];
P.pitchLadrc = [2.5, 120, 1.5, 3, 0.03];
P.pitchEnabled = 1;       % 仿真中设为 1 可观察双轴响应
mw = get_param(model, 'ModelWorkspace');
assignin(mw, 'P', P);

step(model, 'Yaw target', [35 45 80 75], '0.5', '0', '0.6');
step(model, 'Pitch target', [35 105 80 135], '1', '0', '0.25');
step(model, 'Yaw disturbance', [35 230 80 260], '2.3', '0', '0.06');
step(model, 'Pitch disturbance', [35 290 80 320], '2.7', '0', '0.04');
constant(model, 'Yaw LADRC parameters', [100 350 230 380], 'P.yawLadrc');
constant(model, 'Pitch LADRC parameters', [100 390 230 420], 'P.pitchLadrc');
constant(model, 'Pitch enable', [100 430 230 460], 'P.pitchEnabled');
constant(model, 'Motor and load', [410 365 575 395], ...
    '[P.Kt P.Imax P.Jyaw P.Jpitch P.Byaw P.Bpitch P.pitchGravity P.Ts]');

add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [model '/LADRC controller'], 'Position', [290 90 455 275]);
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [model '/Two-axis plant'], 'Position', [640 100 800 305]);
root = sfroot;
c = root.find('-isa', 'Stateflow.EMChart', 'Path', [model '/LADRC controller']);
c.Script = controllerScript();
c = root.find('-isa', 'Stateflow.EMChart', 'Path', [model '/Two-axis plant']);
c.Script = plantScript();

wire(model, 'Yaw target/1', 'LADRC controller/1');
wire(model, 'Pitch target/1', 'LADRC controller/2');
% 显式采样延时用于切断控制器与对象之间的直接馈通环。
% 该延时对应 500 Hz 下的一帧反馈。
for k = 1:4
    name = sprintf('Feedback delay %d', k);
    add_block('simulink/Discrete/Unit Delay', [model '/' name], ...
        'Position', [805 365+45*k 835 390+45*k], ...
        'InitialCondition', '0', 'SampleTime', 'P.Ts');
    wire(model, sprintf('Two-axis plant/%d', k), [name '/1']);
    wire(model, [name '/1'], sprintf('LADRC controller/%d', k+2));
end
wire(model, 'Yaw LADRC parameters/1', 'LADRC controller/7');
wire(model, 'Pitch LADRC parameters/1', 'LADRC controller/8');
wire(model, 'Pitch enable/1', 'LADRC controller/9');
wire(model, 'LADRC controller/1', 'Two-axis plant/1');
wire(model, 'LADRC controller/2', 'Two-axis plant/2');
wire(model, 'Yaw disturbance/1', 'Two-axis plant/3');
wire(model, 'Pitch disturbance/1', 'Two-axis plant/4');
wire(model, 'Motor and load/1', 'Two-axis plant/5');

add_block('simulink/Signal Routing/Mux', [model '/Angles'], ...
    'Inputs', '4', 'Position', [900 20 905 125]);
wire(model, 'Yaw target/1', 'Angles/1');
wire(model, 'Two-axis plant/1', 'Angles/2');
wire(model, 'Pitch target/1', 'Angles/3');
wire(model, 'Two-axis plant/2', 'Angles/4');
add_block('simulink/Sinks/Scope', [model '/Angle scope'], ...
    'Position', [980 55 1020 95]);
wire(model, 'Angles/1', 'Angle scope/1');

add_block('simulink/Signal Routing/Mux', [model '/Currents'], ...
    'Inputs', '2', 'Position', [900 165 905 230]);
wire(model, 'Two-axis plant/5', 'Currents/1');
wire(model, 'Two-axis plant/6', 'Currents/2');
add_block('simulink/Sinks/Scope', [model '/Current scope'], ...
    'Position', [980 180 1020 220]);
wire(model, 'Currents/1', 'Current scope/1');

add_block('simulink/Signal Routing/Mux', [model '/Rates'], ...
    'Inputs', '2', 'Position', [900 260 905 320]);
wire(model, 'Two-axis plant/3', 'Rates/1');
wire(model, 'Two-axis plant/4', 'Rates/2');
add_block('simulink/Sinks/Scope', [model '/Rate scope'], ...
    'Position', [980 275 1020 315]);
wire(model, 'Rates/1', 'Rate scope/1');

logSignal(model, 'Yaw angle log', [1080 15 1200 45], 'yaw_angle', 'Two-axis plant/1');
logSignal(model, 'Pitch angle log', [1080 55 1200 85], 'pitch_angle', 'Two-axis plant/2');
logSignal(model, 'Yaw rate log', [1080 95 1200 125], 'yaw_rate', 'Two-axis plant/3');
logSignal(model, 'Pitch rate log', [1080 135 1200 165], 'pitch_rate', 'Two-axis plant/4');
logSignal(model, 'Yaw current log', [1080 175 1200 205], 'yaw_current', 'Two-axis plant/5');
logSignal(model, 'Pitch current log', [1080 215 1200 245], 'pitch_current', 'Two-axis plant/6');
logSignal(model, 'Yaw target log', [1080 255 1200 285], 'yaw_target', 'Yaw target/1');
logSignal(model, 'Pitch target log', [1080 295 1200 325], 'pitch_target', 'Pitch target/1');
logSignal(model, 'Yaw command log', [1080 335 1200 365], 'yaw_command', 'LADRC controller/1');
logSignal(model, 'Pitch command log', [1080 375 1200 405], 'pitch_command', 'LADRC controller/2');
logSignal(model, 'Yaw disturbance log', [1080 415 1200 445], 'yaw_disturbance', 'Yaw disturbance/1');
logSignal(model, 'Pitch disturbance log', [1080 455 1200 485], 'pitch_disturbance', 'Pitch disturbance/1');

set_param(model, 'SimulationCommand', 'update');
save_system(model, fullfile(here, [model '.slx']));
fprintf('Saved %s\n', fullfile(here, [model '.slx']));
close_system(model);
end

function step(model, name, pos, time, before, after)
add_block('simulink/Sources/Step', [model '/' name], 'Position', pos, ...
    'Time', time, 'Before', before, 'After', after, 'SampleTime', 'P.Ts');
end

function constant(model, name, pos, value)
add_block('simulink/Sources/Constant', [model '/' name], ...
    'Position', pos, 'Value', value);
end

function wire(model, src, dst)
add_line(model, src, dst, 'autorouting', 'on');
end

function logSignal(model, name, pos, variable, src)
add_block('simulink/Sinks/To Workspace', [model '/' name], ...
    'Position', pos, 'VariableName', variable, 'SaveFormat', 'Timeseries');
wire(model, src, [name '/1']);
end

function s = controllerScript()
s = sprintf('%s\n', ...
'function [uy,up] = fcn(ry,rp,y,p,wy,wp,py,pp,pitchEnable)', ...
'%#codegen', ...
'% 仿真使用 Yaw LADRC，并可选择启用 Pitch。', ...
'persistent sy sp wasOn', ...
'if isempty(wasOn)', ...
'    sy = zeros(1,11); sp = zeros(1,11); wasOn = false;', ...
'end', ...
'if ~wasOn', ...
'    sy = [y wy y wy 0 0 0 0 0 0 0];', ...
'    sp = [p wp p wp 0 0 0 0 0 0 0];', ...
'    wasOn = true;', ...
'end', ...
'% Pitch 软件限位和欧拉角奇异性保护。', ...
'rp = min(max(rp,-1.22173048),1.22173048);', ...
'if abs(p)>1.22173048', ...
'    uy=0; up=0; wasOn=false; return;', ...
'end', ...
'[uy,sy] = axisStep(ry,y,sy,py,0.002);', ...
'if pitchEnable~=0', ...
'    [up,sp] = axisStep(rp,p,sp,pp,0.002);', ...
'else', ...
'    up = 0;', ...
'end', ...
'end', ...
'function [u,s] = axisStep(ref,fb,s,q,T)', ...
'% 状态包括 v1、v2、z1、z2、z3、上次导数和指令。', ...
'halfT = 0.5*T;', ...
'fbContinuous = s(3)+circleError(fb,s(3));', ...
'refContinuous = fbContinuous+circleError(ref,fb);', ...
'r=q(1); b0=q(2); wc=q(3); w0=q(4); limit=q(5);', ...
'fh = -r*r*(s(1)-refContinuous)-2*r*s(2);', ...
's(2) = s(2)+halfT*(fh+s(7));', ...
's(1) = s(1)+halfT*(s(2)+s(6));', ...
's(7) = fh; s(6) = s(2);', ...
'e = s(3)-fbContinuous;', ...
'dz3 = -w0*w0*w0*e;', ...
'dz2 = s(5)-3*w0*w0*e+b0*s(11);', ...
'dz1 = s(4)-3*w0*e;', ...
's(5) = s(5)+halfT*(dz3+s(10));', ...
's(4) = s(4)+halfT*(dz2+s(9));', ...
's(3) = s(3)+halfT*(dz1+s(8));', ...
's(10)=dz3; s(9)=dz2; s(8)=dz1;', ...
'u = (wc*wc*(s(1)-s(3))+2*wc*(s(2)-s(4))-s(5))/b0;', ...
'if ~isfinite(u) || ~all(isfinite(s))', ...
'    s=[fb 0 fb 0 0 0 0 0 0 0 0]; u=0;', ...
'end', ...
'u = min(max(u,-limit),limit); s(11)=u;', ...
'end', ...
'function e = circleError(a,b)', ...
'e=a-b;', ...
'if e>pi, e=e-2*pi; elseif e<-pi, e=e+2*pi; end', ...
'end');
end

function s = plantScript()
s = sprintf('%s\n', ...
'function [yaw,pitch,wy,wp,iy,ip] = fcn(uy,up,dy,dp,p)', ...
'%#codegen', ...
'% 定步长近似，未使用实测装配惯量或电机内环模型。', ...
'persistent x', ...
'if isempty(x), x=zeros(1,4); end', ...
'yaw=x(1); pitch=x(2); wy=x(3); wp=x(4);', ...
'iy=min(max(uy,-1),1)*p(2);', ...
'ip=min(max(up,-1),1)*p(2);', ...
'tauY=p(1)*iy+dy;', ...
'tauP=p(1)*ip+dp-p(7)*sin(pitch);', ...
'ay=(tauY-p(5)*wy)/p(3);', ...
'ap=(tauP-p(6)*wp)/p(4);', ...
'x(3)=wy+p(8)*ay; x(4)=wp+p(8)*ap;', ...
'x(1)=yaw+p(8)*x(3); x(2)=pitch+p(8)*x(4);', ...
'end');
end
